/**
 * Generator: plugin.json
 * Deterministic structure + optional LLM fill for description/params/examples.
 * MUST produce valid JSON — JSON.parse validated before return.
 */

/**
 * Generate plugin.json content.
 * @param {object} ctx  { meta, skillDir, existingSkillMd, existingFiles }
 * @param {object|null} llm
 * @returns {Promise<{ content: string, method: 'llm'|'template' }>}
 */
async function generate(ctx, llm = null) {
  if (llm) {
    try {
      return await _generateWithLLM(ctx, llm);
    } catch {
      // fall through to template
    }
  }
  return { content: _template(ctx), method: "template" };
}

function _buildBase(meta = {}) {
  return {
    hubId: meta.slug || "skill",
    name: meta.name || meta.slug || "skill",
    active: false,
    description:
      meta.description ||
      meta.summary ||
      `${meta.title || meta.name || "Skill"} — generated by Skill Completer`,
    setup_args: {},
    entrypoint: {
      params: {
        input: {
          type: "string",
          description: "用户输入",
        },
      },
    },
    examples: [
      {
        prompt: `使用 ${meta.title || meta.name || "skill"}`,
        call: JSON.stringify({ input: "示例输入" }),
      },
    ],
  };
}

function _template(ctx) {
  const obj = _buildBase(ctx.meta);
  return JSON.stringify(obj, null, 2);
}

async function _generateWithLLM(
  { meta = {}, existingSkillMd = "", existingFiles = [] },
  llm
) {
  const systemPrompt = `你是 AnythingLLM Agent Skill 的 plugin.json 参数设计助手。
根据 SKILL.md 文档推断合适的入参字段名和示例。
只返回一个 JSON 对象（不要 \`\`\` 包裹），格式：
{
  "description": "...",
  "params": { "paramName": { "type": "string", "description": "..." } },
  "examples": [{ "prompt": "...", "call": "{...json string...}" }]
}
params 通常 1-3 个，类型仅用 string。examples 1-2 条。`;

  const userPrompt = `Skill 名称：${meta.title || meta.name || meta.slug}
SKILL.md 内容（前 600 字）：
${existingSkillMd.slice(0, 600)}`;

  const llmPart = await llm.generate(systemPrompt, userPrompt, { json: true });

  const base = _buildBase(meta);
  if (llmPart && typeof llmPart === "object") {
    if (
      typeof llmPart.description === "string" &&
      llmPart.description.length > 5
    ) {
      base.description = llmPart.description;
    }
    if (llmPart.params && typeof llmPart.params === "object") {
      base.entrypoint.params = llmPart.params;
    }
    if (Array.isArray(llmPart.examples) && llmPart.examples.length > 0) {
      base.examples = llmPart.examples;
    }
  }

  const content = JSON.stringify(base, null, 2);
  // Validate
  JSON.parse(content);
  return { content, method: "llm" };
}

module.exports = { generate };
