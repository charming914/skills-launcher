/**
 * Generator: handler.js
 *
 * ⚠️  SECURITY NOTICE: The generated handler.js will run in the main process
 * with full system privileges (fs, network, shell). It requires admin approval
 * before activation (active=false). A syntax check via `node --check` is always
 * performed before writing.
 *
 * Default conservative skeleton avoids generating shell/network/fs-write unless
 * explicitly described in SKILL.md. High-risk operations get TODO placeholders.
 */

const { execSync } = require("child_process");
const fs = require("fs");
const path = require("path");
const os = require("os");

const AI_GENERATED_HEADER =
  "// AI-generated by Skill Completer — review before enabling. Runs in main process with full privileges.\n";

/**
 * Generate handler.js content.
 * @param {object} ctx  { meta, skillDir, existingSkillMd, existingPluginJson }
 * @param {object|null} llm
 * @returns {Promise<{ content: string, method: 'llm'|'template' }>}
 */
async function generate(ctx, llm = null) {
  if (llm) {
    // Try LLM, retry once, then fall through
    for (let attempt = 0; attempt < 2; attempt++) {
      try {
        const result = await _generateWithLLM(ctx, llm);
        const validated = await _syntaxCheck(result.content);
        if (validated) return { content: result.content, method: "llm" };
        // syntax failed — retry
      } catch {
        // retry
      }
    }
    // fall through to template
  }
  return { content: _template(ctx), method: "template" };
}

/**
 * Run `node --check` on a temp file. Returns true if syntax is valid.
 * @param {string} code
 * @returns {Promise<boolean>}
 */
async function _syntaxCheck(code) {
  const tmpFile = path.join(
    os.tmpdir(),
    `skill-handler-check-${Date.now()}.js`
  );
  try {
    fs.writeFileSync(tmpFile, code, "utf8");
    execSync(`node --check "${tmpFile}"`, {
      timeout: 10000,
      stdio: "pipe",
      windowsHide: true,
    });
    return true;
  } catch {
    return false;
  } finally {
    try {
      fs.unlinkSync(tmpFile);
    } catch {
      // ignore
    }
  }
}

function _buildParams(pluginJson = null) {
  const params = pluginJson?.entrypoint?.params || {};
  const keys = Object.keys(params);
  if (keys.length === 0) return '{ input = "" }';
  return `{ ${keys.join(", ")} }`;
}

function _template({ meta = {}, existingPluginJson = null }) {
  const params = _buildParams(existingPluginJson);
  const name = meta.title || meta.name || meta.slug || "skill";

  return `${AI_GENERATED_HEADER}
module.exports.runtime = {
  execute: async function (${params}) {
    // TODO: Implement the core logic of "${name}" here.
    // This is a template skeleton generated by Skill Completer.
    // Replace this placeholder with your actual implementation.

    // Example: process input and return a result
    const result = \`Skill "${name}" received input: \${JSON.stringify(arguments[0])}\`;

    return {
      success: true,
      output: result,
    };
  },
};
`;
}

async function _generateWithLLM(
  { meta = {}, existingSkillMd = "", existingPluginJson = null },
  llm
) {
  const params = _buildParams(existingPluginJson);
  const name = meta.title || meta.name || meta.slug || "skill";
  const description = meta.description || meta.summary || "";

  const systemPrompt = `你是 AnythingLLM Agent Skill 的 handler.js 实现助手。
必须输出合法的 Node.js 代码，导出 module.exports.runtime = { execute: async function(...) { return { success, output }; } }。
参数从已知的 plugin.json 解构。
安全约束（必须遵守）：
- 除非 SKILL.md 明确描述需要，不要生成 shell 执行、网络请求、文件写入等高风险操作
- 高风险操作用 TODO 注释占位并返回安全默认值
- 不要引入 require('child_process') 或 require('fs') 写入
只输出 JavaScript 代码，不要 \`\`\` 包裹。`;

  const userPrompt = `Skill 名称：${name}
描述：${description}
入参解构：${params}
SKILL.md（前 800 字）：
${existingSkillMd.slice(0, 800)}`;

  const code = await llm.generate(systemPrompt, userPrompt, { json: false });
  if (!code || typeof code !== "string" || code.length < 30) {
    throw new Error("LLM returned empty handler.js");
  }
  // Must contain runtime.execute
  if (!code.includes("runtime") || !code.includes("execute")) {
    throw new Error("LLM output missing runtime.execute");
  }

  const withHeader = AI_GENERATED_HEADER + "\n" + code.trim() + "\n";
  return { content: withHeader, method: "llm" };
}

module.exports = { generate, _syntaxCheck };
